// Usage: node scripts/desktop-check.mjs (against http://localhost:8000)
import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
await page.goto('http://localhost:8000/', { waitUntil: 'networkidle' })
await wait(2500)
console.log('map canvas', await page.locator('.map-host canvas').count(), 'map status', (await page.locator('.map-status').textContent().catch(() => '-'))?.trim().slice(0, 40))
await page.goto('http://localhost:8000/kanji/%E6%98%8E', { waitUntil: 'networkidle' })
await wait(1200)
console.log('graph nodes', await page.locator('.graph-svg .node').count(), 'zoom buttons', await page.locator('.map-zoom button').count(), 'lock', await page.locator('.graph-lock').count())
const t0 = await page.locator('.graph-svg > g').first().getAttribute('transform')
await page.mouse.move(1000, 300); await page.mouse.down(); await page.mouse.move(1030, 290, { steps: 8 }); await page.mouse.up()
await wait(300)
console.log('drag moved graph', t0 !== (await page.locator('.graph-svg > g').first().getAttribute('transform')))
await page.mouse.wheel(0, 300); await wait(300)
console.log('wheel changed transform', t0 !== (await page.locator('.graph-svg > g').first().getAttribute('transform')))
await page.locator('.graph-svg .node[data-kind="component"]').first().click(); await wait(800)
console.log('clicked component -> page', (await page.locator('.page-head .detail-glyph').first().textContent())?.trim(), 'graph still on', (await page.locator('.graph-svg .node[data-kind="focus"] text').first().textContent())?.trim())
// Associations: a page of their own, from the button beside Statistics.
console.log('rail tabs gone', (await page.locator('.rail-tabs').count()) === 0)
await page.locator('.notes-chip').first().click(); await wait(800)
console.log('associations page', decodeURI(new URL(page.url()).pathname), 'composer', await page.locator('.tab-pane .composer, .tab-pane textarea, .tab-pane [contenteditable]').count() > 0)
await page.locator('.rail-back').click(); await wait(800)
console.log('back from associations', decodeURI(new URL(page.url()).pathname))
// The trail: the way back, then the pages before it.
await page.locator('.vocab-row').nth(3).click(); await wait(1000)
await page.locator('.entry-kanji-glyph:not([data-current])').first().click(); await wait(1000)
console.log('trail', (await page.locator('.rail-trail').innerText()).replace(/\s+/g, ' '))
// The head folds as the page scrolls.
await page.locator('.rail-body').evaluate((el) => (el.scrollTop = 400)); await wait(400)
console.log('head folded', await page.locator('.page-head[data-collapsed]').count())
await page.fill('.search-input', 'water'); await wait(1200)
console.log('desktop word rows', await page.locator('.word').count())
await page.locator('.searchbar-tool').first().click(); await wait(800)
console.log('draw pad', await page.locator('.drawpad').count())
await page.keyboard.press('Escape')
await page.locator('.profile-button').first().click(); await wait(800)
console.log('account dialog', await page.locator('.overlay').count())
console.log('errors', errors)
await browser.close()
