// Usage: node scripts/webkit-cards-video.mjs <dir>  -- WebKit (an iPhone's engine): a video of opening cards 2 and 3 and an Associations card. Frames: ffmpeg -i <dir>/*.webm <dir>/f/%04d.png (Playwright ships one in ms-playwright/ffmpeg-*); a frame with no content (flat, near one colour) is a flash.
import { webkit, devices } from 'playwright'
const DIR = process.argv[2]
const browser = await webkit.launch()
const ctx = await browser.newContext({ ...devices['iPhone 14'], locale: 'en', recordVideo: { dir: DIR, size: { width: 390, height: 664 } } })
await ctx.addInitScript(() => localStorage.setItem('betterrtk:installGuideSeen', '1'))
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
await page.goto('http://localhost:8000/', { waitUntil: 'networkidle' })
await wait(800)
await page.locator('.searchbar input').fill('明')
await wait(1200)
await page.locator('.kanji-hit').first().tap()
await wait(2000)
const two = await page.locator('.page-card:not([data-copy]) .vocab-word').evaluateAll((ws) => ws.findIndex((w) => (w.textContent.match(/[一-鿿]/g) ?? []).length >= 2))
await page.locator('.rail-body').evaluate((el) => (el.scrollTop = 0))
await wait(500)
await page.locator('.page-card:not([data-copy]) .vocab-row').nth(two).tap()
await wait(1500)
await page.locator('.page-card:not([data-copy]) .entry-char', { hasNotText: '明' }).first().tap()
await wait(1500)
await page.locator('.page-card:not([data-copy]) .notes-chip').first().tap()
await wait(1500)
console.log('at', decodeURIComponent(await page.evaluate(() => location.pathname)), 'errors', errors)
const video = page.video()
await ctx.close()
console.log('video', await video.path())
await browser.close()
